// 获取装备数据
function getEquipment(type) {
  const base = EquipmentDatabase[type];
  if (!base) return null;
  return { ...base, type };
}

// 装备克制关系
const EquipmentCounters = {
  tank: ['air_defense', 'helicopter', 'fighter'],
  infantry: ['tank', 'apc', 'artillery'],
  helicopter: ['air_defense', 'fighter'],
  fighter: ['air_defense', 'fighter'],
  bomber: ['fighter', 'air_defense'],
  ship: ['submarine', 'bomber'],
  submarine: ['destroyer', 'helicopter']
};

// 计算装备间伤害加成
function getDamageModifier(attackerType, targetType) {
  const counters = EquipmentCounters[attackerType] || [];
  if (counters.includes(targetType)) return 1.5;
  return 1.0;
}

